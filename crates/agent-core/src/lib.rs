//! # Pocket Agent core
//!
//! The on-device brain of Pocket Agent, compiled to `libpocket_agent_core.so`
//! for Android and exposed to Kotlin through UniFFI. It decides *what* to do;
//! the Kotlin app (via [`bridge::PhoneBridge`]) does it.
//!
//! Module map, roughly in the order a command flows through them:
//!
//! - [`agent`]: the exported [`agent::Agent`] object and onboarding helpers
//! - [`router`]: the router turn (command → tool call → intent)
//! - [`tools`]: tool registry, one module per tool
//! - [`safety`]: confirmation / deny policy, enforced in code
//! - [`client`]: Messages API client (relay or direct), retries, errors
//! - [`api`]: Messages API wire types
//! - [`prompts`]: static system prompts (cache-stable)
//! - [`settings`]: user settings and the atomic on-disk store
//! - [`i18n`]: spoken messages generated by Rust
//! - [`types`] / [`bridge`]: FFI data types and the Kotlin callback interface
//!
//! Threading: everything is blocking and runs on the caller's thread (Kotlin
//! uses `Dispatchers.IO`). There is no async runtime in the library.

uniffi::setup_scaffolding!();

